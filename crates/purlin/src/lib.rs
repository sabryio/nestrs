//! # purlin
//!
//! NestJS-style architecture for Rust: **modules** that declare what they provide
//! and export, **dependency injection** keyed by type or `dyn Trait`, and
//! **controllers** whose routes are plain `async fn` methods, all compiled down to
//! an ordinary [`axum::Router`](http::axum::Router).
//!
//! This is the crate applications depend on; it re-exports the pieces of
//! `purlin-core`, `purlin-http` and `purlin-macros`.
//!
//! ```ignore
//! use purlin::prelude::*;
//!
//! #[injectable]
//! pub struct Greeter;
//!
//! #[injectable]
//! pub struct GreetController { greeter: Arc<Greeter> }
//!
//! #[controller("/greet")]
//! impl GreetController {
//!     #[get("/{name}")]
//!     async fn hello(&self, Path(name): Path<String>) -> String { format!("Hello, {name}") }
//! }
//!
//! #[module(providers = [Greeter], controllers = [GreetController])]
//! pub struct AppModule;
//!
//! #[tokio::main]
//! async fn main() -> Result<(), AppError> {
//!     App::create(AppModule).await?.listen("0.0.0.0:3000").await
//! }
//! ```

#![forbid(unsafe_code)]

// Lets the code generated by the macros say `::purlin::..` even inside this crate.
extern crate self as purlin;

pub use async_trait::async_trait;
/// The headless application framework purlin is built on: constructors, invokes,
/// decorators, modules with private scope, lifecycle hooks and a graceful runtime.
/// Everything in it works without the `http` feature.
pub use fx;
pub mod hosting;
pub use purlin_core::*;
#[cfg(feature = "http")]
pub use purlin_macros::controller;
pub use purlin_macros::{injectable, lifecycle, module, port, provider};

/// The HTTP adapter (`App`, `Guard`, `ValidatedJson`, `HttpError`, re-exported `axum`).
#[cfg(feature = "http")]
pub mod http {
    pub use purlin_http::*;
}

#[cfg(feature = "http")]
/// OpenAPI generation. Derive `ToSchema` on request and response
/// types and `IntoParams` on query structs; your crate needs a
/// direct `utoipa` dependency for the derives to compile.
pub mod openapi {
    pub use purlin_http::openapi::{ApiInfo, BodyDoc, ResponseDoc, RouteDoc};
    pub use purlin_http::utoipa;
    pub use purlin_http::utoipa::{IntoParams, ToSchema};
}

/// Layered, typed, validated configuration.
pub mod config {
    pub use purlin_config::*;
}

#[cfg(feature = "http")]
pub use purlin_http::{App, AppBuilder, AppError, Guard, HttpError, Parts, ValidatedJson};

/// Everything a typical module file needs.
pub mod prelude {
    pub use std::sync::Arc;

    pub use purlin_core::{
        Container, Dependency, DiError, Injectable, Lifetime, Module, ModuleDef, ModuleRef, Multi, OnModuleDestroy,
        OnModuleInit, Overrides, Provider, RequestScope, Token,
    };
    pub use purlin_core::{bind, contribute};
    pub use purlin_macros::{injectable, lifecycle, module, port, provider};

    pub use crate::async_trait;

    #[cfg(feature = "http")]
    pub use purlin_core::Controller;
    #[cfg(feature = "http")]
    pub use purlin_http::axum::Json;
    // No axum `State` here on purpose: shared state is injected (controller fields or `Inject<T>`).
    #[cfg(feature = "http")]
    pub use purlin_http::axum::extract::{Path, Query};
    #[cfg(feature = "http")]
    pub use purlin_http::axum::http::StatusCode;
    #[cfg(feature = "http")]
    pub use purlin_http::{
        App, AppError, Event, EventStream, ExceptionFilter, Guard, HttpError, HttpModule, Inject, Interceptor, KeyBy,
        LastEventId, Parts, Pipe, Piped, Principal, RateLimit, RequestInfo, Timeout, ValidatedJson,
    };
    #[cfg(feature = "http")]
    pub use purlin_macros::controller;
}
