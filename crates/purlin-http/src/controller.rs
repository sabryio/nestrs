use std::sync::Arc;

use crate::openapi::RouteDoc;
use axum::Router;
use axum::http::StatusCode;
use axum::response::{IntoResponse, Response};
use purlin_core::{Container, ControllerEntry, DiError, Injectable, Provider, Token, Transport};

/// The HTTP transport: mounting a controller yields its routes and their docs.
pub struct HttpTransport;

/// What mounting an HTTP controller produces.
pub struct HttpRoutes {
    /// The controller's routes.
    pub router: Router,
    /// One entry per route, for OpenAPI generation.
    pub docs: Vec<RouteDoc>,
}

impl Transport for HttpTransport {
    type Mounted = HttpRoutes;
}

/// What `#[controller]` implements.
///
/// `routes` is called once, after the whole graph is built, with the controller
/// resolved from the container. It returns a router already nested under no
/// prefix: [`join_path`](crate::join_path) applies [`PREFIX`](Self::PREFIX) per route.
pub trait HttpController: Injectable {
    /// Common path prefix of every route.
    const PREFIX: &'static str;

    /// Guards used by this controller's routes. They are not needed to *build* the
    /// controller, but they must exist and be visible, so they are declared as
    /// extra dependencies and checked at bootstrap.
    fn guard_tokens() -> Vec<Token> {
        Vec::new()
    }

    /// Providers that handlers resolve per request through `Inject<T>` / `Piped<P>`.
    /// They must exist and be visible, but may be request-scoped or transient.
    fn request_tokens() -> Vec<Token> {
        Vec::new()
    }

    /// Describes every route for OpenAPI generation. Generated by `#[controller]`.
    fn docs() -> Vec<RouteDoc> {
        Vec::new()
    }

    /// Builds the routes, resolving guards and interceptors from `container`.
    fn routes(self: Arc<Self>, container: &Container) -> Result<Router, DiError>;
}

/// Registers `C` as a controller on the HTTP transport.
pub fn mount<C: HttpController>() -> ControllerEntry {
    let provider = Provider::of::<C>()
        .with_extra_dependencies(C::guard_tokens())
        .with_request_dependencies(C::request_tokens());
    ControllerEntry::new::<HttpTransport>(provider, |container| {
        let controller = container.resolve::<C>()?;
        Ok(HttpRoutes {
            router: controller.routes(container)?,
            docs: C::docs(),
        })
    })
}

/// Compile-time assertion that `T` can be extracted from request parts.
///
/// Emitted by `#[controller]` once per handler parameter, spanned on the
/// parameter's type, so a bad extractor is reported at the parameter rather than
/// as a generic `Handler<_, _>` failure on the whole impl block.
#[doc(hidden)]
pub fn assert_parts_extractor<T: axum::extract::FromRequestParts<()>>() {}

/// Like [`assert_parts_extractor`], for the final parameter, which may consume the body.
#[doc(hidden)]
pub fn assert_last_extractor<T, M>()
where
    T: axum::extract::FromRequest<(), M>,
{
}

/// Applies a route's declared `#[status(..)]`: a handler that answered with the
/// default `200 OK` is answered with `status` instead. Anything else the handler
/// chose (an error, an explicit status, a redirect) is left alone.
pub fn with_default_status<R: IntoResponse>(status: u16, response: R) -> Response {
    let mut response = response.into_response();
    if response.status() == StatusCode::OK
        && let Ok(status) = StatusCode::from_u16(status)
    {
        *response.status_mut() = status;
    }
    response
}
